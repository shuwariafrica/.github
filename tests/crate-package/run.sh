#!/usr/bin/env bash
# Runs crate-package's step over a workspace made here (tests/crates.sh), with the real cargo and
# rustc of an installed exact release: RUST_TOOLCHAINS, a directory of rustup toolchains
# (<release>-x86_64-unknown-linux-gnu), by default RUSTUP_HOME's or ~/.rustup's. rustup itself is
# stood in for at the runner's ~/.cargo/bin/rustup, since rustup reads its channel from the network
# even for an installed release: it records its words, installs only a release present there, and
# names that release's cargo.
# Usage: run.sh [--tree <directory>] [<case>...]; tests/crates.sh says the rest.
# Needs gpg, gpgconf, git, jq, yq (mikefarah's), sha256sum, od, cmp and an installed toolchain.
set -euo pipefail
shopt -s inherit_errexit
unset CDPATH

HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
readonly HERE
# shellcheck source=tests/step.sh
. "${HERE}/../step.sh"
# shellcheck source=tests/crates.sh
. "${HERE}/../crates.sh"
TOOLS=(od cmp)

TOOLCHAINS=${RUST_TOOLCHAINS:-${RUSTUP_HOME:-${HOME}/.rustup}/toolchains}
RELEASE=$(find "${TOOLCHAINS}/" -mindepth 1 -maxdepth 1 -regextype posix-extended \
  -regex '.*/[0-9]+\.[0-9]+\.[0-9]+-x86_64-unknown-linux-gnu' -printf '%f\n' | sort -V | tail -n1)
RELEASE=${RELEASE%-x86_64-unknown-linux-gnu}
[[ -n ${RELEASE} ]] || {
  printf 'no exact release installed in %s\n' "${TOOLCHAINS}" >&2
  exit 69
}
readonly TOOLCHAINS RELEASE

# The runner's home in the case <dir>: the rustup stand-in at .cargo/bin/rustup.
home() {
  local d=$1
  mkdir -p -- "${d}/home/.cargo/bin"
  cat >"${d}/home/.cargo/bin/rustup" <<STUB
#!/usr/bin/env bash
# rustup's stand-in for this case: its words recorded; \`toolchain install\` and \`which\` answered
# for the releases installed in ${TOOLCHAINS}, as rustup answers once a release is installed.
set -euo pipefail
printf '%s\n' "\$*" >>'${d}/stub/rustup'
case \$1 in
  toolchain) release=\${!#} ;;
  which) release=\$3 ;;
  *) exit 1 ;;
esac
[[ -x ${TOOLCHAINS}/\${release}-x86_64-unknown-linux-gnu/bin/cargo ]] || {
  printf 'error: toolchain %s is not installable here\n' "\${release}" >&2
  exit 1
}
[[ \$1 != which ]] || printf '%s\n' '${TOOLCHAINS}/'"\${release}"'-x86_64-unknown-linux-gnu/bin/cargo'
STUB
  chmod 755 -- "${d}/home/.cargo/bin/rustup"
}

pfile() { # case, path, content: the project's file
  mkdir -p -- "$(dirname -- "$1/workspace/project/$2")"
  printf '%s' "$3" >"$1/workspace/project/$2"
}

# The project's workspace in the case <dir>: probe-a and probe-b at 0.1.0, neither depending on the
# other, so cargo reads no registry; its lock; a CHANGELOG.md with the version's entry.
project() {
  local d=$1
  mkdir -p -- "${d}/workspace/project"
  pfile "${d}" Cargo.toml '[workspace]
members = ["crates/*"]
resolver = "3"

[workspace.package]
version = "0.1.0"
edition = "2024"
license = "Apache-2.0"
description = "a probe"
'
  pfile "${d}" crates/probe-a/Cargo.toml '[package]
name = "probe-a"
version.workspace = true
edition.workspace = true
license.workspace = true
description.workspace = true
readme = "README.md"
'
  pfile "${d}" crates/probe-a/README.md '# probe-a
'
  pfile "${d}" crates/probe-a/src/lib.rs ''
  pfile "${d}" crates/probe-b/Cargo.toml '[package]
name = "probe-b"
version.workspace = true
edition.workspace = true
license.workspace = true
description.workspace = true
'
  pfile "${d}" crates/probe-b/src/lib.rs ''
  pfile "${d}" Cargo.lock '# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "probe-a"
version = "0.1.0"

[[package]]
name = "probe-b"
version = "0.1.0"
'
  pfile "${d}" CHANGELOG.md '# Changelog

## 0.1.0

The first.

## 0.0.9

Before.
'
  pfile "${d}" rust-toolchain.toml "[toolchain]
channel = \"${RELEASE}\"
"
  home "${d}"
}

commit_project() {
  local d=$1
  git -C "${d}/workspace/project" init --quiet -b main 2>/dev/null || true # already one after the first commit
  git -C "${d}/workspace/project" add -A
  git -C "${d}/workspace/project" -c user.name=t -c user.email=t@example.invalid commit --quiet --no-gpg-sign --allow-empty -m state
  SHA=$(git -C "${d}/workspace/project" rev-parse HEAD)
}

package() {
  local d=$1
  run_script "${d}" crate-package/package-step.sh HOME="${d}/home" CHECKOUT=project TOOLCHAIN="${TOOLCHAIN_OVER:-${RELEASE}}" \
    VERSION=0.1.0 CRATES="${CRATES_OVER:-[\"probe-a\",\"probe-b\"]}" SHA="${SHA_OVER:-${SHA}}" GITHUB_WORKSPACE="${d}/workspace"
}

case_package_writes_each_crate_its_body_the_order_the_entry_and_sums() {
  local d out digest crate json_length json named listing vcs
  d=$(fresh packages)
  project "${d}"
  commit_project "${d}"
  package "${d}"
  expect "${d}" 0 'packaged probe-a, probe-b at 0.1.0'
  out=$(output_of "${d}" directory)
  digest=$(sha256sum "${out}/SHA256SUMS" | cut -d' ' -f1)
  out_is "${d}" digest "${digest}"
  named=$(awk '{print $2}' "${out}/SHA256SUMS")
  [[ ${named//$'\n'/ } == 'probe-a-0.1.0.crate probe-b-0.1.0.crate probe-a-0.1.0.upload probe-b-0.1.0.upload order changelog.md' ]] ||
    fail "SHA256SUMS names ${named//$'\n'/ }"
  (cd -- "${out}" && sha256sum --check --strict --quiet SHA256SUMS) || fail 'a file is not its sum'
  [[ $(<"${out}/order") == $'probe-a\nprobe-b' ]] || fail "order $(<"${out}/order")"
  [[ $(<"${out}/changelog.md") == $'## 0.1.0\n\nThe first.' ]] || fail "changelog.md $(<"${out}/changelog.md")"
  # shellcheck source=actions/crate-publish/lib.sh
  . "${TREE}/actions/crate-publish/lib.sh"
  for crate in probe-a probe-b; do
    # shellcheck disable=SC2310
    # body_carries's status is its answer.
    body_carries "${out}/${crate}-0.1.0.upload" "${out}/${crate}-0.1.0.crate" "${crate}" 0.1.0 || fail "${crate}'s body does not carry its crate"
  done
  json_length=$(od --address-radix=n --format=u4 --endian=little --read-bytes=4 -- "${out}/probe-a-0.1.0.upload")
  json_length=${json_length//[[:space:]]/}
  json=$(dd if="${out}/probe-a-0.1.0.upload" iflag=skip_bytes,count_bytes skip=4 count="${json_length}" bs=65536 status=none)
  json=$(jq -c '[.readme, .readme_file]' <<<"${json}")
  [[ ${json} == '["# probe-a\n","README.md"]' ]] || fail "probe-a's body gives the readme ${json}"
  listing=$(tar -tzf "${out}/probe-a-0.1.0.crate")
  grep -qx 'probe-a-0.1.0/.cargo_vcs_info.json' <<<"${listing}" || fail 'the crate names no commit'
  vcs=$(tar -xzOf "${out}/probe-a-0.1.0.crate" probe-a-0.1.0/.cargo_vcs_info.json)
  grep -q "\"sha1\": \"${SHA}\"" <<<"${vcs}" || fail 'the crate names another commit'
  grep -qx "toolchain install --profile minimal --no-self-update ${RELEASE}" "${d}/stub/rustup" || fail "rustup ran $(<"${d}/stub/rustup")"
}

case_the_step_runs_as_its_action_step_runs_it() {
  local d
  d=$(fresh wired)
  project "${d}"
  commit_project "${d}"
  input=([path]=project [toolchain]="${RELEASE}" [version]=0.1.0 [crates]='["probe-a","probe-b"]')
  over=([SHA]="${SHA}")
  caller=(PATH=/usr/bin:/bin "HOME=${d}/home" LANG=C.UTF-8)
  wired "${d}" crate-package 0
  expect "${d}" 0 'packaged probe-a, probe-b at 0.1.0'
}

# Each way the tree could run code while packaged, each writing <dir>/marker.
markers() {
  local d=$1 fake
  pfile "${d}" crates/probe-a/build.rs "fn main() { std::fs::write(\"${d}/marker\", \"build.rs\").unwrap(); }
"
  pfile "${d}" .cargo/config.toml "[build]
rustc-wrapper = \"${d}/workspace/project/wrapper.sh\"
"
  pfile "${d}" wrapper.sh "#!/bin/sh
echo rustc-wrapper >>'${d}/marker'
exec \"\$@\"
"
  chmod 755 "${d}/workspace/project/wrapper.sh"
  pfile "${d}" rust-toolchain 'marker-legacy
'
  fake=${d}/workspace/project/fake-toolchain
  mkdir -p -- "${fake}/bin"
  for tool in cargo rustc; do
    printf '#!/bin/sh\necho %s-from-path >>"%s/marker"\nexit 1\n' "${tool}" "${d}" >"${fake}/bin/${tool}"
    chmod 755 "${fake}/bin/${tool}"
  done
  pfile "${d}" rust-toolchain.toml "[toolchain]
path = \"${fake}\"
"
}

case_package_runs_nothing_of_the_tree() {
  local d
  d=$(fresh markers)
  project "${d}"
  markers "${d}"
  commit_project "${d}"
  package "${d}"
  expect "${d}" 0 'packaged probe-a, probe-b at 0.1.0'
  [[ ! -e ${d}/marker ]] || fail "the tree ran: $(<"${d}/marker")"
  ! grep -q marker-legacy "${d}/stub/rustup" || fail 'rustup read the legacy toolchain file'
}

case_a_crate_outside_admits_is_refused() {
  local d
  d=$(fresh outside)
  project "${d}"
  commit_project "${d}"
  CRATES_OVER='["probe-a"]' package "${d}"
  expect "${d}" 1 'cargo packaged [probe-a-0.1.0.crate probe-b-0.1.0.crate], and admit admitted [probe-a-0.1.0.crate]'
  out_is "${d}" digest ''
}

case_a_checkout_not_the_runs_or_not_clean_is_refused() {
  local d
  d=$(fresh not_the_runs)
  project "${d}"
  commit_project "${d}"
  SHA_OVER=$(printf '%040d' 6) package "${d}"
  expect "${d}" 1 'and the run'"'"'s commit is 0000000000000000000000000000000000000006'
  d=$(fresh dirty)
  project "${d}"
  commit_project "${d}"
  printf 'x\n' >"${d}/workspace/project/untracked"
  package "${d}"
  expect "${d}" 1 'the checkout is not clean: ?? untracked'
}

case_a_toolchain_not_one_exact_release_is_refused() {
  local d
  d=$(fresh toolchain)
  project "${d}"
  commit_project "${d}"
  TOOLCHAIN_OVER=stable package "${d}"
  expect "${d}" 1 'not one exact release: stable'
  [[ ! -s ${d}/stub/rustup ]] || fail 'rustup ran'
}

crates_main "$@"
